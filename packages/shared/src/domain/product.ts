/**
 * The rules every FINAL variant list must satisfy, whatever produced it (create, or an update merged
 * with the existing variants). Returns the first Persian error message, or null.
 */
export function validateVariantSet(variants: { unit: string; price: number }[]): string | null {
  if (variants.length === 0) return "حداقل یک واحد فروش لازم است";
  const seen = new Set<string>();
  for (const v of variants) {
    if (!(PRODUCT_UNITS as readonly string[]).includes(v.unit)) return "واحد فروش نامعتبر است";
    if (!Number.isInteger(v.price) || v.price < 1) return "قیمت باید یک عدد صحیح و حداقل ۱ تومان باشد";
    if (seen.has(v.unit)) return PRODUCT_DUPLICATE_UNIT_MESSAGE;
    seen.add(v.unit);
  }
  return null;
}

